let questions = [];
let currentQuestion = 0;
let score = 0;
let answers = [];

const questionElement = document.getElementById("question");
const optionButtons = document.querySelectorAll(".option-btn");
const nextBtn = document.getElementById("next-btn");
const prevBtn = document.getElementById("prev-btn");
const resultBox = document.getElementById("result-box");
const quizBox = document.getElementById("quiz-box");
const userScore = document.getElementById("user-score");
const resultMessage =
document.getElementById("result-message");

const yesBtn =
document.getElementById("yes-btn");

const noBtn =
document.getElementById("no-btn");
const questionNumber = document.getElementById("question-number");

function startQuiz(category) {

    questions = questionBank[category];

    currentQuestion = 0;
    score = 0;

    answers = new Array(questions.length).fill("");

    document.getElementById("category-box").style.display = "none";

    quizBox.style.display = "block";

    resultBox.style.display = "none";

    showQuestion();
}

function showQuestion() {

    let q = questions[currentQuestion];

    questionNumber.innerText =
        `Question ${currentQuestion + 1} of ${questions.length}`;

    questionElement.innerText = q.question;

    const letters = ["A", "B", "C", "D"];

    optionButtons.forEach((button, index) => {

        button.innerText =
            "○ " + letters[index] + ". " + q.options[index];

        button.style.backgroundColor = "";

        if (answers[currentQuestion] === q.options[index]) {

            button.style.backgroundColor = "#90EE90";

        }

        button.onclick = function () {

            answers[currentQuestion] = q.options[index];

            optionButtons.forEach(btn => {

                btn.style.backgroundColor = "";

            });

            button.style.backgroundColor = "#90EE90";

        };
    });
}

nextBtn.addEventListener("click", () => {

    if (answers[currentQuestion] === "") {
        alert("Please select an answer!");
        return;
    }

    if (currentQuestion < questions.length - 1) {

        currentQuestion++;

        showQuestion();

    } else {

        calculateScore();

        showResult();
    }
});

prevBtn.addEventListener("click", () => {

    if (currentQuestion > 0) {

        currentQuestion--;

        showQuestion();
    }
});

function calculateScore() {

    score = 0;

    for (let i = 0; i < questions.length; i++) {

        if (answers[i] === questions[i].answer) {

            score++;
        }
    }
}

function showResult() {

    quizBox.style.display = "none";

    resultBox.style.display = "block";

    let percentage =
    (score / questions.length) * 100;

    if(percentage >= 80){

        resultMessage.innerHTML =
        "🎉 Congratulations! Excellent Performance!";

    }
    else if(percentage >= 60){

        resultMessage.innerHTML =
        "👏 Good Job! Keep Learning!";

    }
    else{

        resultMessage.innerHTML =
        "📚 Keep Practicing! You Can Improve!";
    }

    userScore.innerHTML =
    `You scored ${score} out of ${questions.length}`;

}

yesBtn.addEventListener("click", () => {

    currentQuestion = 0;

    score = 0;

    answers = [];

    resultBox.style.display = "none";

    document.getElementById("category-box").style.display = "block";

});

noBtn.addEventListener("click", () => {

    resultBox.innerHTML = `

        <h2>🙏 Thank You For Using The Quiz App</h2>

        <p>
            Keep Learning and Keep Growing!
        </p>

        <h3>See You Again!</h3>

    `;

});